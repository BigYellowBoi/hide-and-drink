#!/usr/bin/env python3
"""Generate the seed-content migration from data/*.json.

Supabase's GitHub integration only applies migrations to production (seed.sql is
ignored), so the starting card library, questions and play areas ship as a migration.
Rows are inserted with ON CONFLICT DO NOTHING, so later in-app edits are never
overwritten. Once a migration has been applied, never edit it: to add new rows
from data/*.json later, write a NEW migration file with this script (existing rows
are skipped; changes to existing rows need their own UPDATE migration).

Usage:
    python3 scripts/seed_to_sql.py supabase/migrations/<timestamp>_seed_content.sql
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"


def lit(value) -> str:
    """SQL literal for a Python value."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        return lit(json.dumps(value, ensure_ascii=False, separators=(",", ":"))) + "::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def generate() -> str:
    cards_doc = json.loads((DATA / "cards.json").read_text())
    questions_doc = json.loads((DATA / "questions.json").read_text())
    play_areas = sorted((DATA / "play-areas").glob("*.geojson"))

    out = [
        "-- Generated by scripts/seed_to_sql.py from data/*.json. Do not edit by hand.",
        "-- Seeds the starting content. ON CONFLICT DO NOTHING keeps later in-app edits.",
        "",
    ]

    for i, cat in enumerate(cards_doc["categories"]):
        out.append(
            "insert into public.categories (id, name, colour, sort) values "
            f"({lit(cat['id'])}, {lit(cat['name'])}, {lit(cat['colour'])}, {i}) "
            "on conflict (id) do nothing;"
        )
    out.append("")

    for i, c in enumerate(cards_doc["cards"]):
        params = dict(c.get("params") or {})
        if c.get("todo"):
            params["todo"] = c["todo"]
        out.append(
            "insert into public.cards (id, name, category_id, behaviour, body, params, cast_cost, "
            "can_veto, default_copies, sort, active) values ("
            + ", ".join(
                [
                    lit(c["id"]),
                    lit(c["name"]),
                    lit(c["category"]),
                    lit(c["behaviour"]),
                    lit(c.get("text")),
                    lit(params),
                    lit(c.get("cast_cost")),
                    lit(c.get("can_veto")),
                    lit(c["copies"]),
                    lit(i),
                    lit(c.get("active", True)),
                ]
            )
            + ") on conflict (id) do nothing;"
        )
    out.append("")

    city = questions_doc["city"]
    core = {"type", "prompt", "reward", "auto_shading", "options"}
    for i, q in enumerate(questions_doc["types"]):
        extra = {k: v for k, v in q.items() if k not in core}
        out.append(
            "insert into public.question_types (city, type, prompt, reward_draw, reward_pick, "
            "auto_shading, options, extra, sort) values ("
            + ", ".join(
                [
                    lit(city),
                    lit(q["type"]),
                    lit(q["prompt"]),
                    lit(q["reward"]["draw"]),
                    lit(q["reward"]["pick"]),
                    lit(q["auto_shading"]),
                    lit(q["options"]),
                    lit(extra),
                    lit(i),
                ]
            )
            + ") on conflict (city, type) do nothing;"
        )
    out.append("")

    for path in play_areas:
        fc = json.loads(path.read_text())
        name = fc["features"][0]["properties"].get("name", path.stem)
        out.append(
            "insert into public.play_areas (name, city, geojson) values "
            f"({lit(name)}, {lit(city)}, {lit(fc)}) on conflict (city, name) do nothing;"
        )

    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__)
        return 2
    target = Path(argv[0])
    target.write_text(generate())
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
