"""Turn a city pack into a migration that (re)loads it into PostGIS.

The migration calls public._load_city_pack(jsonb), which replaces every feature for the
city in one transaction. Never edit an applied migration: rebuild the pack and write a new one.
"""

from __future__ import annotations

import json
from pathlib import Path


def migration_sql(pack: dict, source_name: str) -> str:
    body = json.dumps(pack, ensure_ascii=False, separators=(",", ":"))
    tag = "pack"
    while f"${tag}$" in body:
        tag += "_"
    meta = pack["pack"]
    counts = ", ".join(f"{layer['id']}={layer['count']}" for layer in meta["layers"])
    return (
        f"-- Generated by `python3 -m pipeline sql` from {source_name}. Do not edit by hand.\n"
        f"-- City pack: {meta['city']}, built {meta['built_at']}.\n"
        f"-- Layers: {counts}\n"
        f"select public._load_city_pack(${tag}${body}${tag}$::jsonb);\n"
    )


def write(pack_path: Path, out: Path, root: Path) -> None:
    pack = json.loads(pack_path.read_text())
    out.write_text(migration_sql(pack, str(pack_path.resolve().relative_to(root))))
